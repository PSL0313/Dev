import Foundation

enum AgreementDocument {
    case termsOfService
    case personalInformationConsent
    case privacyPolicy

    var title: String {
        switch self {
        case .termsOfService:
            return "서비스 이용약관"

        case .personalInformationConsent:
            return "개인정보 수집·이용 동의"

        case .privacyPolicy:
            return "개인정보처리방침"
        }
    }

    var content: String {
        switch self {
        case .termsOfService:
            return Self.termsOfServiceContent

        case .personalInformationConsent:
            return Self.personalInformationConsentContent

        case .privacyPolicy:
            return Self.privacyPolicyContent
        }
    }
}

extension AgreementDocument: Identifiable {

    var id: String {
        switch self {
        case .termsOfService:
            return "termsOfService"

        case .personalInformationConsent:
            return "personalInformationConsent"

        case .privacyPolicy:
            return "privacyPolicy"
        }
    }
}

